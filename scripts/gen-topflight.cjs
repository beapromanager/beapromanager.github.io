// Turns the approved ליגת העל drafts (PIC/team/top-flight/*.json) into src/data/topFlightText.ts.
//   node scripts/gen-topflight.cjs
const fs = require('fs');
const rd = n => JSON.parse(fs.readFileSync(`PIC/team/top-flight/${n}.json`, 'utf8'));

// the example names the export was rendered with, put back as slots
const BACK = [['הסוכן של דני כהן', 'הסוכן של {who}'], ['עין סלע', '{city}'], ['איציק', '{mgr}']];
const slot = s => typeof s === 'string' ? BACK.reduce((t, [a, b]) => t.split(a).join(b), s) : s;
const deep = o => Array.isArray(o) ? o.map(deep) : o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, deep(v)])) : slot(o);

const dil = [...rd('dilemmas-1'), ...rd('dilemmas-2')];
const opt = o => ({ label: o.label, outcome: o.outcome, money: o.money || 0, morale: o.morale || 0, fans: o.fans || 0, prestige: o.prestige || 0 });
const dilBody = x => ({ speaker: x.speaker, text: x.text, variants: x.variants || [], options: x.options.map(opt) });
const DILEMMA_REWRITE = {}, DILEMMA_NEW = {}, DILEMMA_DROP = [];
for (const x of dil) {
  if (x.action === 'rewrite') DILEMMA_REWRITE[x.id] = dilBody(x);
  else if (x.action === 'new') DILEMMA_NEW[x.id] = dilBody(x);
  else if (x.action === 'drop') DILEMMA_DROP.push(x.id);
}

const press = rd('press');
const ans = a => ({ label: a.label, reply: a.reply });
const PRESS_REWRITE = {}, PRESS_NEW = {}, PRESS_DROP = [];
for (const x of press) {
  if (x.action === 'rewrite' && x.id !== 'own_goal') PRESS_REWRITE[x.id] = { text: x.text, answers: x.answers.map(ans) };
  else if (x.action === 'new') PRESS_NEW[x.id] = { text: x.text, answers: x.answers.map(ans) };
  else if (x.action === 'drop') PRESS_DROP.push(x.id);
}

const line = l => { const i = l.indexOf(': '); return i < 0 ? { from: l.endsWith(':') ? '' : '', text: l } : { from: l.slice(0, i), text: l.slice(i + 2) }; };
const chat = x => ({ contact: x.contact, subtitle: x.subtitle, group: /משתתפים/.test(x.subtitle), lines: x.lines.map(line) });
const CHAT_REWRITE = {}, CHAT_NEW = {};
for (const x of rd('chats')) {
  if (x.action === 'rewrite') CHAT_REWRITE[x.id] = chat(x);
  else if (x.action === 'new') CHAT_NEW[x.id] = chat(x);
}
const MATE = {};
for (const x of rd('mate')) if (x.action === 'rewrite') MATE[x.id] = { lines: x.lines, answers: x.answers.map(ans) };
const FAN_REWRITE = {}, FAN_NEW = {};
for (const x of rd('fans')) {
  if (x.action === 'rewrite') FAN_REWRITE[x.id] = { when: x.when, text: x.text };
  else if (x.action === 'new') FAN_NEW[x.id] = { when: x.when, text: x.text };
}

const out = `/**
 * ליגת העל from the ground up (Itzik, 13.10: "הכל כמו שהוא תכניס למשחק"). The text of the approved drafts, nothing else:
 * which of it is offered, and when, is decided where it is used (dilemmas.ts, press.ts, chats.ts, fans.ts, state.ts).
 * Generated by scripts/gen-topflight.cjs from PIC/team/top-flight/*.json. The sums are final ליגת העל sums.
 */
export interface TopOption { label: string; outcome: string; money: number; morale: number; fans: number; prestige: number }
export interface TopDilemma { speaker: string; text: string; variants: string[]; options: TopOption[] }
export interface TopAnswer { label: string; reply: string }
export interface TopQuestion { text: string; answers: TopAnswer[] }
export interface TopChat { contact: string; subtitle: string; group: boolean; lines: { from: string; text: string }[] }
export interface TopFan { when: string; text: string }

export const TOP_DILEMMA_REWRITE: Record<string, TopDilemma> = ${JSON.stringify(DILEMMA_REWRITE, null, 1)};
export const TOP_DILEMMA_NEW: Record<string, TopDilemma> = ${JSON.stringify(DILEMMA_NEW, null, 1)};
export const TOP_DILEMMA_DROP: string[] = ${JSON.stringify(DILEMMA_DROP)};

export const TOP_PRESS_REWRITE: Record<string, TopQuestion> = ${JSON.stringify(PRESS_REWRITE, null, 1)};
export const TOP_PRESS_NEW: Record<string, TopQuestion> = ${JSON.stringify(PRESS_NEW, null, 1)};
export const TOP_PRESS_DROP: string[] = ${JSON.stringify(PRESS_DROP)};

export const TOP_CHAT_REWRITE: Record<string, TopChat> = ${JSON.stringify(deep(CHAT_REWRITE), null, 1)};
export const TOP_CHAT_NEW: Record<string, TopChat> = ${JSON.stringify(deep(CHAT_NEW), null, 1)};

export const TOP_MATE: Record<string, { lines: string[]; answers: TopAnswer[] }> = ${JSON.stringify(MATE, null, 1)};

export const TOP_FAN_REWRITE: Record<string, TopFan> = ${JSON.stringify(FAN_REWRITE, null, 1)};
export const TOP_FAN_NEW: Record<string, TopFan> = ${JSON.stringify(FAN_NEW, null, 1)};
`;
// the press text carries {city} where the draft had the example town
fs.writeFileSync('src/data/topFlightText.ts', out.replace(/עין סלע/g, '{city}'));
console.log(Object.keys(DILEMMA_REWRITE).length, Object.keys(DILEMMA_NEW).length, DILEMMA_DROP.length, Object.keys(PRESS_REWRITE).length, Object.keys(PRESS_NEW).length, Object.keys(CHAT_REWRITE).length, Object.keys(CHAT_NEW).length, Object.keys(FAN_REWRITE).length, Object.keys(FAN_NEW).length);
