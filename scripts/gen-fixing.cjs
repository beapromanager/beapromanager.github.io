// Turns the writer's draft (PIC/team/fixing/content.json) into src/data/fixingText.ts, with Itzik's house polish on a few lines.
//   node scripts/gen-fixing.cjs
const fs = require('fs');
const c = JSON.parse(fs.readFileSync('PIC/team/fixing/content.json', 'utf8'));

// the weight of each situation: a small favour pays little, a big one pays a lot (the odds are always the same)
const WEIGHT = { fix_01: 1.0, fix_02: 1.2, fix_03: 1.5, fix_04: 1.5, fix_05: 1.2, fix_06: 1.8, fix_07: 1.0, fix_08: 2.0, fix_09: 1.3, fix_10: 2.5 };

// polish: lines that were clumsy when read aloud
const FIX = {
  caught: {
    title: 'דפקו בדלת',
    body: 'האיגוד סגר את המועדון הבוקר. ועדת המשמעת פירסמה הודעה קצרה, והעיר קראה אותה בעמוד הראשון.\nאתה כבר לא המאמן. המועדון נסגר, ואתה מתחיל מחדש בליגה ג׳.',
  },
  rescue: {
    title: 'מישהו עדיין מתקשר',
    body: 'מועדון קטן בליגה ג׳ מתקשר בכל זאת. הם צריכים מאמן, והם יודעים שאתה יודע לנצח.\nכולם בעיר יודעים מה עשית, וכולם מתעלמים בנימוס.\nזו הזדמנות שנייה. אין שלישית.',
  },
};

const sits = c.situations.map((s, i) => ({
  id: s.id, title: s.title, tag: s.tag, text: s.text, yes: s.yes, no: s.no, yesOutcome: s.yesOutcome, noOutcome: s.noOutcome,
  image: `/fix/s${String(i + 1).padStart(2, '0')}.webp`, weight: WEIGHT[s.id],
}));
const out = `/**
 * The ten situations of "the owner asks to sell a match", and the words of the match, the wait and the verdict (the content
 * writer's drafts of 14.10). Generated by scripts/gen-fixing.cjs from PIC/team/fixing/content.json. {rival}, {star}, {sum} are slots.
 */
export interface FixSituation {
  id: string; title: string; tag: string; text: string; yes: string; no: string; yesOutcome: string; noOutcome: string;
  image: string; weight: number;
}
export const FIX_SITUATIONS: FixSituation[] = ${JSON.stringify(sits, null, 1)};
export const FIX_MATCH_LINES: string[] = ${JSON.stringify(c.matchLines, null, 1)};
export const FIX_SUSPENSE: string[] = ${JSON.stringify(c.suspense, null, 1)};
export const FIX_CAUGHT_TEXT = ${JSON.stringify({ ...c.caught, ...FIX.caught }, null, 1)};
export const FIX_CLEAR_TEXT = ${JSON.stringify(c.clear, null, 1)};
export const FIX_SACKED_TEXT = ${JSON.stringify(c.sacked, null, 1)};
export const FIX_RESCUE_TEXT = ${JSON.stringify({ ...c.rescue, ...FIX.rescue }, null, 1)};
`;
fs.writeFileSync('src/data/fixingText.ts', out);
console.log(sits.length, 'situations');
