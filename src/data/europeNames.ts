/** A full name for a man of that country, never one already in the squad. */
export function makeEuroName(rng: Rng, country: string, used: Set<string>): string {
  const bank = EURO_NAMES[country];
  if (!bank) return `שחקן ${Math.floor(rng() * 90) + 10}`;
  for (let i = 0; i < 60; i++) {
    const name = `${bank.first[Math.floor(rng() * bank.first.length)]} ${bank.last[Math.floor(rng() * bank.last.length)]}`;
    if (!used.has(name)) { used.add(name); return name; }
  }
  const name = `${bank.first[0]} ${bank.last[Math.floor(rng() * bank.last.length)]} ${used.size}`;
  used.add(name);
  return name;
}
